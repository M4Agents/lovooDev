async function asRole(db, role, run) {
  await db.exec(`SET ROLE ${role}`);
  try {
    return await run();
  } finally {
    await db.exec('RESET ROLE');
  }
}

async function commit(db, body) {
  const { rows } = await asRole(db, 'service_role', () => db.query(
    'SELECT public.nuvemshop_welcome_commit_signup($1::jsonb) AS result',
    [JSON.stringify(body)],
  ));
  return rows[0].result;
}

